         if (!File.Exists(appInitPath))
         {
            //load example
            TextAsset appInit = (TextAsset)AssetDatabase.LoadAssetAtPath("Packages/com.reborn.reborncore/Editor/Examples/APPInit.txt", typeof(TextAsset));

            FileStream fs = new FileStream(appInitPath, FileMode.Create);
            StreamWriter sw = new StreamWriter(fs);
            sw.Write(appInit.text);
            sw.Flush();
            sw.Close();
            sw.Dispose();
         }

         //生成UpdateLauncher.cs
         var launcherPath = Path.Combine(Application.dataPath, "Scripts", "Core", "AppUpdate.cs");
         
            if (!File.Exists(launcherPath))
            {
               //load example
               TextAsset appUpdate = (TextAsset)AssetDatabase.LoadAssetAtPath("Packages/com.reborn.reborncore/Editor/Examples/AppUpdate.txt", typeof(TextAsset));

               FileStream fs = new FileStream(launcherPath, FileMode.Create);
               StreamWriter sw = new StreamWriter(fs);
               sw.Write(appUpdate.text);
               sw.Flush();
               sw.Close();
               sw.Dispose();
                
