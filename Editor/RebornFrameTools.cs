using System.Collections;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;

public class RebornFrameTools : Editor
{
   [MenuItem("RebornFrame/初始化框架", false, 1)]
   public static void InitRebornFrame()
   {
      //生成必要的文件夹
      var path = Path.Combine(Application.dataPath, "Scripts", "Core");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);
      
      
       path = Path.Combine(Application.dataPath, "Arts", "Textures", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Textures", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Materials", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Materials", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Meshes", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Meshes", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Audios", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Audios", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Animations", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Animations", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Prefabs", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Prefabs", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Shaders", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Shaders", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Scenes", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Scenes", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Timeline", "Export");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);

      path = Path.Combine(Application.dataPath, "Arts", "Timeline", "Normal");
      if (!Directory.Exists(path))
         Directory.CreateDirectory(path);
      
      
      

      if (EditorUtility.DisplayDialog("项目确认", "是否为热更项目？", "是", "否"))
      {
         path = Path.Combine(Application.dataPath, "HotUpdate", "Core");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);
         
         path = Path.Combine(Application.dataPath, "HotUpdate", "Configs");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);
         
         path = Path.Combine(Application.dataPath, "HotUpdate", "Configs", "AutoConfigClass");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);
         
         path = Path.Combine(Application.dataPath, "HotUpdate", "Configs", "AutoConfigManager");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);
         
         path = Path.Combine(Application.dataPath, "HotUpdate", "Configs", "ConfigExtend");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);

         path = Path.Combine(Application.dataPath, "HotUpdate", "UI");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);   
         
