            Directory.CreateDirectory(path);
         
         path = Path.Combine(Application.dataPath, "Resources", "Configs", "AutoConfigClass");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);
         
         
         path = Path.Combine(Application.dataPath, "Resources", "Configs","AutoConfigManager");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);
         
         path = Path.Combine(Application.dataPath, "Resources", "Configs","ConfigExtend");
