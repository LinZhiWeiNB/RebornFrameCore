            Directory.CreateDirectory(path);
         
         path = Path.Combine(Application.dataPath, "Scripts", "UI");
         if (!Directory.Exists(path))
            Directory.CreateDirectory(path);
         
         path = Path.Combine(Application.dataPath, "Scripts", "Configs");
